# Variable Naming Rules
# 1. A variable MUST start with a letter and cannot start with a number
# 2. A variable can be a mixed of letters and numbers BUT not symbols
# 3. A variale CANNOT be a Python keyword

appleCount = 42
numberofStudents = 27
